/**
 * Represents the keyboard input state for the game.
 * Each property is `true` while the corresponding key is held down.
 */
class Keyboard {
    /** Whether the left arrow key is pressed. */
    LEFT = false;
    /** Whether the right arrow key is pressed. */
    RIGHT = false;
    /** Whether the up arrow key is pressed. */
    UP = false;
    /** Whether the down arrow key is pressed. */
    DOWN = false;
    /** Whether the space bar is pressed. */
    SPACE = false;
    /** Whether the D key is pressed (throw bottle). */
    D = false;
}
